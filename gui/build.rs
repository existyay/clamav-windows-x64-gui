/// Format a byte count for the build log.
///
/// Integer kilobyte division used to turn any file smaller than 1 KB into a
/// meaningless "0 KB -> 0 KB", which is exactly the size most of the YAMAGoya
/// rules are.
fn human_size(bytes: usize) -> String {
    const KB: f64 = 1024.0;
    const MB: f64 = KB * 1024.0;

    let bytes_f = bytes as f64;
    if bytes_f < KB {
        format!("{} B", bytes)
    } else if bytes_f < MB {
        format!("{:.1} KB", bytes_f / KB)
    } else {
        format!("{:.1} MB", bytes_f / MB)
    }
}

/// 递归收集并压缩 embed 目录中的所有文件。
fn collect_and_compress_files(
    base: &std::path::Path,
    dir: &std::path::Path,
    compressed_dir: &std::path::Path,
    entries: &mut Vec<(String, String)>,
) {
    let Ok(rd) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in rd.filter_map(|e| e.ok()) {
        let path = entry.path();
        if path.is_dir() {
            collect_and_compress_files(base, &path, compressed_dir, entries);
        } else if path.is_file() {
            let ext = path
                .extension()
                .map(|e| e.to_string_lossy().to_lowercase())
                .unwrap_or_default();
            if ext == "md" || ext == "txt" {
                continue;
            }
            if let Ok(rel) = path.strip_prefix(base) {
                let rel_str = rel.to_string_lossy().replace('\\', "/");
                // 压缩文件名：将路径分隔符替换为下划线，加 .zst 后缀
                let safe_name = rel_str.replace('/', "_") + ".zst";
                let compressed_path = compressed_dir.join(&safe_name);

                // 读取原始文件并用 zstd 压缩
                if let Ok(raw_data) = std::fs::read(&path) {
                    let compressed = zstd::encode_all(raw_data.as_slice(), 19)
                        .expect("Failed to compress embedded file");
                    std::fs::write(&compressed_path, &compressed)
                        .expect("Failed to write compressed file");

                    // Logged rather than emitted as `cargo:warning=`: these are
                    // informational, and dressing them up as warnings buried the
                    // real ones (and scaled with the number of rule files).
                    // `cargo build -vv` still shows them.
                    println!(
                        "Compressed {}: {} -> {} ({:.0}%)",
                        rel_str,
                        human_size(raw_data.len()),
                        human_size(compressed.len()),
                        compressed.len() as f64 / raw_data.len().max(1) as f64 * 100.0
                    );

                    if let Ok(abs_path) = std::fs::canonicalize(&compressed_path) {
                        // `canonicalize` yields a `\\?\C:\...` verbatim path on
                        // Windows. `include_bytes!` accepts either form, but the
                        // generated manifest is easier to read without the prefix.
                        let abs_str = abs_path.to_string_lossy();
                        let trimmed = abs_str
                            .strip_prefix(r"\\?\")
                            .unwrap_or_else(|| abs_str.as_ref());
                        entries.push((rel_str, trimmed.replace('\\', "/")));
                    }
                }
            }
        }
    }
}
